import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const html = readFileSync("index.html", "utf8");
const pages = readFileSync(".github/workflows/pages.yml", "utf8");
const sw = readFileSync("sw.js", "utf8");
const server = readFileSync("core/server.py", "utf8");
const readme = readFileSync("README.md", "utf8");

assert.match(html, /Ron-1 SmolLM/);
assert.match(html, /fetch\(apiBase\+'\/health'/);
assert.match(html, /fetch\(apiBase\+'\/api\/chat'/);
assert.match(html, /ron1\.nativeApi\.v1/);
assert.match(html, /data\.base_model/);
assert.ok(!html.includes("new Worker("));
assert.ok(!html.includes("ron-model-worker.js"));
assert.ok(!html.includes("onnx-community"));
assert.ok(!html.includes("transformers.min.js"));
assert.match(server, /HuggingFaceTB\/SmolLM3-3B/);
assert.match(server, /AutoModelForCausalLM\.from_pretrained/);
assert.match(server, /apply_chat_template/);
assert.match(server, /\/api\/chat/);
assert.match(server, /\/health/);
assert.match(server, /RON1_ALLOWED_ORIGIN/);
assert.doesNotMatch(server, /ron1-native-state-dict-v1/);
assert.doesNotMatch(server, /checkpoint\.get\("trained"\)/);
assert.match(pages, /cp index\.html sw\.js site\//);
assert.doesNotMatch(pages, /curl.*huggingface|onnx\/model_q4|ron1-q4|cp -R vendor|vendor\/transformers site/i);
assert.match(sw, /ron1-smollm-ui-v2/);
assert.doesNotMatch(sw, /weights|models-v2|vendor\/transformers/i);
assert.match(readme, /pretrained SmolLM weights/);
assert.match(readme, /GitHub Pages only publishes|API must be hosted separately/i);
console.log("Ron-1 SmolLM runtime separation checks passed.");
